import random2

# Эта библиотека нужна для генерации случайных чисел и случайного выбора элементов из списка (аналог стандартного модуля random).
# Она используется в играх, тестах, при проведении розыгрышей и для создания случайных паролей или данных.

# 1. Генерируем случайное число от 1 до 100
secret_number = random2.randint(1, 100)
print(f"Случайное число от 1 до 100: {secret_number}")

# 2. Выбираем случайного победителя из списка
participants = ["Айбек", "Мария", "Тимур", "Алина", "Дмитрий"]
winner = random2.choice(participants)
print(f"Победитель розыгрыша: {winner}")
